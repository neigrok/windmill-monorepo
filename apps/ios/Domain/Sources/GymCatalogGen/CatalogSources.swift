import SyncCore

// The GymDomain Coach catalog source, from packages/api-contract/gym/catalog.json: every ability as Swift data, its input
// and result schemas as literals of SyncCore's JSON. Pure: main.swift reads the file and writes or checks what this answers.

struct GenerationError: Error, CustomStringConvertible {
  let description: String
}

enum CatalogSources {
  static let catalogFile = "packages/api-contract/gym/catalog.json"
  static let generatedFile = "apps/ios/Domain/Sources/GymDomain/Coach/Catalog.generated.swift"
  static let fields = ["name", "description", "input", "result", "class", "agent", "seats", "phrase", "ui"]
  static let classes = ["read", "add", "change", "remove"]
  static let agents = ["runs", "proposes", "withheld"]
  static let seats = ["any", "bound"]

  static func text(from catalog: JSON) throws -> String {
    let object = try unwrap(catalog.asObject(), "the catalog is not an object")
    try unwrap(object.expectKeys(required: ["catalog", "abilities"]), "the catalog's keys")
    let version = try unwrap(object.member("catalog").asString(), "the catalog version")
    let abilities = try unwrap(object.member("abilities").asArray(), "the abilities")
    var text = """
      // Generated by GymCatalogGen from \(catalogFile). Do not edit.

      import SyncCore

      extension Catalog {
        public static let version = \(SwiftLiteral.string(version))

        static let declared: [Ability] = [

      """
    var names: [String] = []
    for entry in abilities {
      let ability = try self.ability(entry)
      guard !names.contains(ability.name) else { throw GenerationError(description: "two abilities are named \(ability.name)") }
      names.append(ability.name)
      text += "    Ability(\n"
      text += "      name: \(SwiftLiteral.string(ability.name)), kind: .\(ability.kind), agent: .\(ability.agent), seats: .\(ability.seats), "
      text += "declared: \(ability.declared),\n"
      text += "      phrase: \(SwiftLiteral.string(ability.phrase)),\n"
      for (label, schema) in [("input", ability.input), ("result", ability.result)] {
        let lead = "      \(label): "
        text += lead + SwiftLiteral.render(schema, indent: 6, column: lead.count) + (label == "input" ? ",\n" : "),\n")
      }
    }
    return text + "  ]\n}\n"
  }

  struct Entry {
    let name: String, kind: String, agent: String, seats: String, phrase: String, declared: Bool
    let input: JSON, result: JSON
  }

  static func ability(_ json: JSON) throws -> Entry {
    let object = try unwrap(json.asObject(), "an ability is not an object")
    try unwrap(object.expectKeys(required: fields, optional: ["declared", "since"]), "an ability's keys")
    let name = try unwrap(object.member("name").asString(), "an ability's name")
    // The version that added the ability: the phone speaks the newest, which offers every ability, so it keeps none.
    if let since = object["since"], !(try unwrap(since.asString(), "\(name).since")).hasPrefix("catalog/") {
      throw GenerationError(description: "\(name).since names no catalog version")
    }
    func word(_ field: String, of allowed: [String]) throws -> String {
      let value = try unwrap(object.member(field).asString(), "\(name).\(field)")
      guard allowed.contains(value) else { throw GenerationError(description: "\(name).\(field) is \(value), none of \(allowed)") }
      return value
    }
    let declared = try unwrap(object["declared"]?.asBool() ?? true, "\(name).declared")
    return Entry(name: name, kind: try word("class", of: classes), agent: try word("agent", of: agents), seats: try word("seats", of: seats),
                 phrase: try unwrap(object.member("phrase").asString(), "\(name).phrase"), declared: declared,
                 input: try object.member("input"), result: try object.member("result"))
  }

  static func unwrap<T>(_ body: @autoclosure () throws -> T, _ what: String) throws -> T {
    do { return try body() } catch { throw GenerationError(description: "\(what): \(error)") }
  }
}

// A JSON value as a Swift literal of SyncCore's JSON, as SyncSchemaGen writes a registry.
enum SwiftLiteral {
  static let width = 120

  // `json` starting at `column` of a line indented by `indent`: on that line when it fits the width with the comma after
  // it, otherwise one member per line.
  static func render(_ json: JSON, indent: Int, column: Int) -> String {
    let inline = self.inline(json)
    guard column + inline.count + 1 > width, let members = members(of: json) else { return inline }
    let pad = String(repeating: " ", count: indent + 2)
    let lines = members.map { member in
      let label = member.key.map { "\(string($0)): " } ?? ""
      return pad + label + render(member.value, indent: indent + 2, column: pad.count + label.count) + ","
    }
    return "[\n" + lines.joined(separator: "\n") + "\n" + String(repeating: " ", count: indent) + "]"
  }

  static func inline(_ json: JSON) -> String {
    switch json {
    case .null: return ".null"
    case .bool(let flag): return flag ? "true" : "false"
    case .number(let number): return self.number(number)
    case .string(let text): return string(text)
    case .array(let items): return "[" + items.map(inline).joined(separator: ", ") + "]"
    case .object(let object):
      guard !object.isEmpty else { return "[:]" }
      return "[" + object.members.map { "\(string($0.key)): \(inline($0.value))" }.joined(separator: ", ") + "]"
    }
  }

  static func members(of json: JSON) -> [(key: String?, value: JSON)]? {
    switch json {
    case .array(let items) where !items.isEmpty: items.map { (key: nil, value: $0) }
    case .object(let object) where !object.isEmpty: object.members.map { (key: $0.key, value: $0.value) }
    default: nil
    }
  }

  // A safe integer is an integer literal; any other number a float literal, which Swift rounds to the same double.
  static func number(_ number: JSON.Number) -> String {
    let text = number.description
    if number.value.rounded() == number.value && number.value.magnitude <= Double(JSON.maxSafeInteger) { return text }
    return text.contains { $0 == "." || $0 == "e" } ? text : text + ".0"
  }

  // A string literal holding exactly the text's scalars: printable ASCII as itself, every other scalar escaped.
  static func string(_ text: String) -> String {
    var literal = "\""
    for scalar in text.unicodeScalars {
      switch scalar {
      case "\"": literal += "\\\""
      case "\\": literal += "\\\\"
      case " "..."~": literal.unicodeScalars.append(scalar)
      default: literal += "\\u{\(String(scalar.value, radix: 16, uppercase: true))}"
      }
    }
    return literal + "\""
  }
}
