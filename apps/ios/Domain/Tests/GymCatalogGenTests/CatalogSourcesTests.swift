import Foundation
import SyncCore
import Testing

@testable import GymCatalogGen

// The generator's source, text for text, and the checked-in file against what the catalog generates today.
struct CatalogSourcesTests {
  static func repository() throws -> URL {
    var root = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    while !FileManager.default.fileExists(atPath: root.appendingPathComponent(CatalogSources.catalogFile).path) {
      try #require(root.path != "/")
      root.deleteLastPathComponent()
    }
    return root
  }

  @Test func theCheckedInCatalogIsWhatTheContractGenerates() throws {
    let root = try Self.repository()
    let catalog = try JSON(parsing: [UInt8](Data(contentsOf: root.appendingPathComponent(CatalogSources.catalogFile))))
    let checkedIn = try String(contentsOf: root.appendingPathComponent(CatalogSources.generatedFile), encoding: .utf8)
    #expect(try CatalogSources.text(from: catalog) == checkedIn, "run swift run GymCatalogGen in apps/ios/Domain")
  }

  @Test func anAbilityIsWrittenAsSwiftDataWithItsSchemasAsLiterals() throws {
    let catalog: JSON = [
      "catalog": "catalog/9",
      "abilities": [[
        "name": "list_notes", "description": "The notes.", "class": "read", "agent": "runs", "seats": "any",
        "phrase": "read your notes", "ui": "Notes", "declared": false,
        "input": ["type": "object", "properties": [:], "required": [], "additionalProperties": false],
        "result": ["type": "object", "properties": ["notes": ["type": "array", "items": ["type": "string", "maxLength": 60]]],
                   "required": ["notes"], "additionalProperties": false],
      ]],
    ]
    #expect(try CatalogSources.text(from: catalog) == """
      // Generated by GymCatalogGen from packages/api-contract/gym/catalog.json. Do not edit.

      import SyncCore

      extension Catalog {
        public static let version = "catalog/9"

        static let declared: [Ability] = [
          Ability(
            name: "list_notes", kind: .read, agent: .runs, seats: .any, declared: false,
            phrase: "read your notes",
            input: ["additionalProperties": false, "properties": [:], "required": [], "type": "object"],
            result: [
              "additionalProperties": false,
              "properties": ["notes": ["items": ["maxLength": 60, "type": "string"], "type": "array"]],
              "required": ["notes"],
              "type": "object",
            ]),
        ]
      }

      """)
  }

  @Test func aCatalogOutsideTheDeclarationIsRefused() throws {
    func entry(_ name: String, kind: String) -> JSON {
      ["name": .string(name), "description": "", "class": .string(kind), "agent": "runs", "seats": "any", "phrase": "", "ui": "",
       "input": [:], "result": [:]]
    }
    #expect(throws: GenerationError.self) { try CatalogSources.text(from: ["catalog": "catalog/1", "abilities": [entry("x", kind: "write")]]) }
    #expect(throws: GenerationError.self) {
      try CatalogSources.text(from: ["catalog": "catalog/1", "abilities": [entry("x", kind: "read"), entry("x", kind: "read")]])
    }
    var later = try entry("x", kind: "read").asObject()
    later["since"] = "2"
    #expect(throws: GenerationError.self) { try CatalogSources.text(from: ["catalog": "catalog/2", "abilities": [.object(later)]]) }
    later["since"] = "catalog/2"
    #expect(try CatalogSources.text(from: ["catalog": "catalog/2", "abilities": [.object(later)]])
      == CatalogSources.text(from: ["catalog": "catalog/2", "abilities": [entry("x", kind: "read")]]))
  }
}
