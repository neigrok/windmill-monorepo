import Foundation
import SyncCore
import Testing

@testable import CatalogGen

// The generator's source, text for text, and each checked-in catalog against what its contract generates today.
struct CatalogSourcesTests {
  static func repository() throws -> URL {
    var root = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    while !FileManager.default.fileExists(atPath: root.appendingPathComponent(CatalogSource.all[0].catalogFile).path) {
      try #require(root.path != "/")
      root.deleteLastPathComponent()
    }
    return root
  }

  @Test(arguments: CatalogSource.all.map(\.product))
  func theCheckedInCatalogIsWhatTheContractGenerates(_ product: String) throws {
    let root = try Self.repository()
    let source = try #require(CatalogSource.all.first { $0.product == product })
    let catalog = try JSON(parsing: [UInt8](Data(contentsOf: root.appendingPathComponent(source.catalogFile))))
    let checkedIn = try String(contentsOf: root.appendingPathComponent(source.generatedFile), encoding: .utf8)
    #expect(try source.text(from: catalog) == checkedIn, "run swift run CatalogGen in apps/ios/Domain")
  }

  @Test func anAbilityIsWrittenAsSwiftDataWithItsSchemasAsLiteralsStrictUnlessItSaysOtherwise() throws {
    let entry: JSON = [
      "name": "list_notes", "description": "The notes.", "class": "read", "agent": "runs", "seats": "any",
      "phrase": "read your notes", "ui": "Notes", "declared": false,
      "input": ["type": "object", "properties": [:], "required": [], "additionalProperties": false],
      "result": ["type": "object", "properties": ["notes": ["type": "array", "items": ["type": "string", "maxLength": 60]]],
                 "required": ["notes"], "additionalProperties": false],
    ]
    var loose = try entry.asObject()
    loose["name"] = "list_trees"
    loose["strict"] = false
    #expect(try CatalogSource(product: "gym", domain: "GymDomain").text(from: ["catalog": "catalog/9", "abilities": [entry, .object(loose)]]) == """
      // Generated by CatalogGen from packages/api-contract/gym/catalog.json. Do not edit.

      import DomainKit
      import SyncCore

      extension Catalog {
        public static let gym = Catalog(version: "catalog/9", abilities: gymAbilities)

        static let gymAbilities: [Ability] = [
          Ability(
            name: "list_notes", kind: .read, agent: .runs, seats: .any, declared: false, strict: true,
            phrase: "read your notes",
            input: ["additionalProperties": false, "properties": [:], "required": [], "type": "object"],
            result: [
              "additionalProperties": false,
              "properties": ["notes": ["items": ["maxLength": 60, "type": "string"], "type": "array"]],
              "required": ["notes"],
              "type": "object",
            ]),
          Ability(
            name: "list_trees", kind: .read, agent: .runs, seats: .any, declared: false, strict: false,
            phrase: "read your notes",
            input: ["additionalProperties": false, "properties": [:], "required": [], "type": "object"],
            result: [
              "additionalProperties": false,
              "properties": ["notes": ["items": ["maxLength": 60, "type": "string"], "type": "array"]],
              "required": ["notes"],
              "type": "object",
            ]),
        ]
      }

      """)
  }

  @Test func aCatalogOutsideTheDeclarationIsRefused() throws {
    let source = CatalogSource(product: "roadmap", domain: "RoadmapDomain")
    func entry(_ name: String, kind: String) -> JSON {
      ["name": .string(name), "description": "", "class": .string(kind), "agent": "runs", "seats": "any", "phrase": "", "ui": "",
       "input": [:], "result": [:]]
    }
    #expect(throws: GenerationError.self) { try source.text(from: ["catalog": "catalog/1", "abilities": [entry("x", kind: "write")]]) }
    #expect(throws: GenerationError.self) {
      try source.text(from: ["catalog": "catalog/1", "abilities": [entry("x", kind: "read"), entry("x", kind: "read")]])
    }
    var later = try entry("x", kind: "read").asObject()
    later["strict"] = "no"
    #expect(throws: GenerationError.self) { try source.text(from: ["catalog": "catalog/2", "abilities": [.object(later)]]) }
    later["strict"] = nil
    later["since"] = "2"
    #expect(throws: GenerationError.self) { try source.text(from: ["catalog": "catalog/2", "abilities": [.object(later)]]) }
    later["since"] = "catalog/2"
    #expect(try source.text(from: ["catalog": "catalog/2", "abilities": [.object(later)]])
      == source.text(from: ["catalog": "catalog/2", "abilities": [entry("x", kind: "read")]]))
  }
}
